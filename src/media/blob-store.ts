/**
 * Byte storage for media, separate from its metadata.
 *
 * The database answers "which assets exist and who may see them"; this port
 * answers "where are the bytes". Keeping them apart is what lets the metadata
 * survive a filesystem hiccup, and what makes a logical backup possible: the
 * manifest and the files are copied together, and each file is checked against
 * the digest in the database rather than assumed to be there.
 *
 * The filesystem implementation is deliberately narrow. It writes into a
 * temporary directory and renames it into place, so a crash leaves either a
 * complete asset or a temporary directory the next start can remove — never a
 * half-written image that a message already references.
 */

import { mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { randomUUID } from 'node:crypto';
import { MediaError } from './errors.ts';

export interface BlobPaths {
  readonly original: string;
  readonly normalized: string;
  readonly request: string;
}

export interface BlobBodies {
  readonly original: Uint8Array;
  readonly normalized: Uint8Array;
  readonly request: Uint8Array;
}

export interface MediaBlobStore {
  put(paths: BlobPaths, bodies: BlobBodies): Promise<void>;
  read(key: string): Promise<Buffer>;
  /** Remove every file recorded for one asset, then its (now empty) directory. */
  remove(paths: BlobPaths): Promise<void>;
  exists(key: string): Promise<boolean>;
}

/**
 * The asset directory is the first three key segments:
 * `<userId>/<conversationId>/<assetId>`. Deriving it from the recorded keys
 * rather than accepting a directory from a caller keeps the deletion surface to
 * paths this process itself created.
 */
export function assetDirectory(paths: BlobPaths): string {
  return dirname(paths.original);
}

export class FileMediaBlobStore implements MediaBlobStore {
  readonly #root: string;

  constructor(root: string) {
    this.#root = resolve(root);
  }

  get root(): string {
    return this.#root;
  }

  async put(paths: BlobPaths, bodies: BlobBodies): Promise<void> {
    const finalDir = this.#resolve(assetDirectory(paths));
    const temporaryKey = join('.tmp', randomUUID());
    const temporary = this.#resolve(temporaryKey);
    try {
      await mkdir(temporary, { recursive: true, mode: 0o700 });
      // `temporary` is already absolute and inside the root; joining directly
      // avoids resolving it a second time as if it were a key.
      await writeFile(join(temporary, basename(paths.original)), bodies.original, {
        mode: 0o600,
      });
      await writeFile(join(temporary, basename(paths.normalized)), bodies.normalized, {
        mode: 0o600,
      });
      await writeFile(join(temporary, basename(paths.request)), bodies.request, {
        mode: 0o600,
      });
      await mkdir(dirname(finalDir), { recursive: true, mode: 0o700 });
      await rename(temporary, finalDir);
    } catch (error) {
      await rm(temporary, { recursive: true, force: true }).catch(() => undefined);
      throw new MediaError('MEDIA_STORE_FAILED', '图片写入失败', 500, {
        retryable: true,
        details: { reason: error instanceof Error ? error.message : String(error) },
      });
    }
  }

  async read(key: string): Promise<Buffer> {
    try {
      return await readFile(this.#resolve(key));
    } catch (error) {
      const code = (error as { code?: unknown }).code;
      throw new MediaError(
        code === 'ENOENT' ? 'MEDIA_NOT_FOUND' : 'MEDIA_STORE_FAILED',
        code === 'ENOENT' ? '图片文件不存在' : '图片读取失败',
        code === 'ENOENT' ? 404 : 500,
      );
    }
  }

  async remove(paths: BlobPaths): Promise<void> {
    await rm(this.#resolve(assetDirectory(paths)), { recursive: true, force: true });
  }

  async exists(key: string): Promise<boolean> {
    try {
      const info = await stat(this.#resolve(key));
      return info.isFile();
    } catch {
      return false;
    }
  }

  /**
   * Resolve a storage key inside the media root.
   *
   * Keys are generated by this process, but this is the one place a corrupted
   * row could become a traversal, so it is checked rather than trusted.
   */
  #resolve(key: string): string {
    if (key.length === 0 || key.startsWith('/') || key.includes('\0')) {
      throw new MediaError('MEDIA_STORE_FAILED', '媒体存储键不合法', 500);
    }
    const absolute = resolve(this.#root, key);
    if (absolute !== this.#root && !absolute.startsWith(`${this.#root}${sep}`)) {
      throw new MediaError('MEDIA_STORE_FAILED', '媒体路径越界', 500);
    }
    return absolute;
  }
}

function basename(key: string): string {
  const index = key.lastIndexOf('/');
  return index === -1 ? key : key.slice(index + 1);
}

/** In-memory bytes, for tests and `STORE=memory`. */
export class MemoryMediaBlobStore implements MediaBlobStore {
  readonly #files = new Map<string, Uint8Array>();

  async put(paths: BlobPaths, bodies: BlobBodies): Promise<void> {
    // Copy, so a caller reusing its buffer cannot mutate a stored asset.
    this.#files.set(paths.original, Uint8Array.from(bodies.original));
    this.#files.set(paths.normalized, Uint8Array.from(bodies.normalized));
    this.#files.set(paths.request, Uint8Array.from(bodies.request));
  }

  async read(key: string): Promise<Buffer> {
    const bytes = this.#files.get(key);
    if (!bytes) throw new MediaError('MEDIA_NOT_FOUND', '图片文件不存在', 404);
    return Buffer.from(bytes);
  }

  async remove(paths: BlobPaths): Promise<void> {
    this.#files.delete(paths.original);
    this.#files.delete(paths.normalized);
    this.#files.delete(paths.request);
  }

  async exists(key: string): Promise<boolean> {
    return this.#files.has(key);
  }
}
